"""Generate STM (Source-to-Target Mapping) Excel workbook for Patient 360 pipeline.

This script produces a complete 8-sheet STM workbook based on:
- DMS-2026-03-16-patient-360.md (target schemas)
- HLD-2026-03-16-patient-360-pipeline.md (architecture context)
- transformation-standards.md (casting, null handling, dedup rules)
- code-system-mappings.md (SNOMED-CT, RxNorm, LOINC, HL7 codes)
- User mapping decisions from elicitation Q&A

Mapping Decisions Applied:
  Q1: Dual hashes (_record_hash full row + _scd2_hash SCD2 columns only)
  Q2: Preserve source column names as-is at Bronze
  Q3: Hash dedup -- SELECT DISTINCT on business key + _record_hash
  Q4: Unmapped code values -> 'UNMAPPED' with _is_unmapped flag
  Q5: COALESCE cost NULLs to 0 at Bronze-to-Silver
  Q6: Surrogate keys via MD5(natural_key) cast to BIGINT
  Q7: SCD2 tracked attributes: address, city, state, county, zip, marital_status
"""

