META_FILL = PatternFill(start_color="E8DAEF", end_color="E8DAEF", fill_type="solid")
WRAP = Alignment(wrap_text=True, vertical="top")


def apply_sheet_formatting(ws, headers, col_fills=None, col_widths=None):
    """Apply standard formatting to a data sheet."""
    # Write headers
    for col_idx, header in enumerate(headers, 1):
        cell = ws.cell(row=1, column=col_idx, value=header)
        cell.font = HEADER_FONT
        cell.alignment = WRAP
        if col_fills and col_idx <= len(col_fills) and col_fills[col_idx - 1]:
            cell.fill = col_fills[col_idx - 1]

    # Freeze top row
    ws.freeze_panes = "A2"

    # Column widths
    if col_widths:
        for col_idx, w in enumerate(col_widths, 1):
            ws.column_dimensions[get_column_letter(col_idx)].width = w
    else:
        for col_idx in range(1, len(headers) + 1):
            ws.column_dimensions[get_column_letter(col_idx)].width = 25


def finalize_autofilter(ws):
    """Set auto-filter after data is written."""
    if ws.max_row and ws.max_row >= 1:
        ws.auto_filter.ref = ws.dimensions


def add_rows(ws, rows):
    """Append data rows and apply wrap alignment."""
    for row_data in rows:
        ws.append(row_data)
    # Apply wrap to all data cells
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row, max_col=ws.max_column):
        for cell in row:
            cell.alignment = WRAP


